/**
 * Smart Project Planner - Groq AI Integration Logic
 * Calls backend /api/ai/generate endpoint to draft technical specs, acceptance criteria, and subtasks.
 */

/**
 * Core function calling backend /api/ai/generate
 */
async function generateAiTaskDescription(title, projectName = '', context = '') {
  const token = getStoredToken();
  const user = getStoredUser();

  const headers = {
    'Content-Type': 'application/json'
  };

  if (token) {
    headers['Authorization'] = `Bearer ${token}`;
  }
  if (user) {
    headers['X-User-Id'] = user.userId;
    headers['X-Company-Id'] = user.companyId;
    headers['X-User-Role'] = user.role;
  }

  const response = await fetch('/api/ai/generate', {
    method: 'POST',
    headers: headers,
    body: JSON.stringify({
      title: title,
      projectName: projectName,
      context: context
    })
  });

  const data = await response.json();
  if (!response.ok || !data.success) {
    throw new Error(data.error || 'Failed to generate AI description');
  }

  return data.description;
}

/**
 * Triggered from Task Creation Modal via "✨ Generate with Groq AI" button
 */
async function triggerAiGenerationForTask() {
  const titleInput = document.getElementById('taskTitleInput');
  const descInput = document.getElementById('taskDescInput');
  const projectSelect = document.getElementById('taskProjectSelect');
  const spinner = document.getElementById('aiGeneratingSpinner');

  const title = titleInput.value.trim();
  if (!title) {
    showToast('Please enter a Task Title first so AI can generate the scope.', 'error');
    titleInput.focus();
    return;
  }

  let projectName = 'Smart Workspace';
  if (projectSelect && projectSelect.selectedIndex > 0) {
    projectName = projectSelect.options[projectSelect.selectedIndex].text;
  }

  if (spinner) spinner.style.display = 'inline';
  descInput.placeholder = 'Groq AI is generating technical requirements and acceptance criteria...';

  try {
    const description = await generateAiTaskDescription(title, projectName, '');
    descInput.value = description;
    showToast('Task specification generated by Groq AI!', 'success');
  } catch (err) {
    showToast('AI Generation Notice: ' + err.message, 'error');
  } finally {
    if (spinner) spinner.style.display = 'none';
    descInput.placeholder = 'Detailed technical scope, checklist, and criteria...';
  }
}

/**
 * Standalone Groq AI Assistant Modal Handlers
 */
function openAiAssistantModal() {
  const modal = document.getElementById('aiModalOverlay');
  if (modal) {
    modal.classList.add('active');
    document.getElementById('aiPromptTitle').focus();
  }
}

function closeAiAssistantModal() {
  const modal = document.getElementById('aiModalOverlay');
  if (modal) modal.classList.remove('active');
}

async function runStandaloneAiSynthesis() {
  const titleInput = document.getElementById('aiPromptTitle');
  const contextInput = document.getElementById('aiPromptContext');
  const outputGroup = document.getElementById('aiOutputGroup');
  const outputArea = document.getElementById('aiOutputArea');
  const btn = document.getElementById('btnRunAiSynthesizer');

  const title = titleInput.value.trim();
  const context = contextInput.value.trim();

  if (!title) {
    showToast('Please enter a title or feature idea.', 'error');
    titleInput.focus();
    return;
  }

  setButtonLoading(btn, true, 'Synthesizing with Groq LLaMA-3...');

  try {
    const description = await generateAiTaskDescription(title, 'General Workspace', context);
    outputArea.value = description;
    outputGroup.style.display = 'block';
    showToast('AI Specification Ready!', 'success');
  } catch (err) {
    showToast('AI error: ' + err.message, 'error');
  } finally {
    setButtonLoading(btn, false, '⚡ Generate Specification');
  }
}

function copyAiOutputToTaskModal() {
  const title = document.getElementById('aiPromptTitle').value.trim();
  const desc = document.getElementById('aiOutputArea').value;

  closeAiAssistantModal();
  openTaskModal();

  const taskTitle = document.getElementById('taskTitleInput');
  const taskDesc = document.getElementById('taskDescInput');

  if (taskTitle) taskTitle.value = title;
  if (taskDesc) taskDesc.value = desc;

  showToast('Copied specification into New Task Modal.', 'info');
}
